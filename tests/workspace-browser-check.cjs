    assert.equal(await page.locator('#dcw-per-page').inputValue(),'7');
    assert.ok(await button('undo').isDisabled());
    const stored=await page.evaluate(()=>chrome.storage.local.get(null));
    assert.ok(Object.values(stored).some(v=>v?.books?.length===1),'Other project should survive switching');
    assert.ok(!JSON.stringify(stored).includes('data:image/'),'Image bytes must not bloat draft storage');
