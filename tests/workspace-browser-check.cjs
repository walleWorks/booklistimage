    await page.waitForFunction(()=>document.querySelector('.dcw-book-card img')?.naturalWidth>0);await saved();
    assert.equal(await page.locator('.dcw-missing-cover').count(),22);
    await page.locator('#dcw-view-filter').selectOption('missing');await cards(22);
    await page.locator('#dcw-view-filter').selectOption('all');await cards(23);
