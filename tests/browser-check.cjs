// Run against fixture-server.cjs with Playwright installed (no real Douban requests).
const {chromium} = require('playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
(async()=>{
  const browser=await chromium.launch({channel:'chrome',headless:true});
  try {
    const page=await browser.newPage({viewport:{width:1440,height:960},acceptDownloads:true});
    const errors=[];page.on('pageerror',err=>errors.push(err.message));
    await page.route('https://img.doubanio.com/**',route=>route.fulfill({contentType:'image/svg+xml',body:'<svg xmlns="http://www.w3.org/2000/svg" width="240" height="360"><rect width="240" height="360" fill="#31584c"/><text x="24" y="100" font-size="24" fill="white">TEST BOOK</text></svg>'}));
    const url='http://127.0.0.1:8768/personage/1/creations?type=writer';
    await page.goto(url);
    await page.locator('#dcw-launcher').click();
    await page.waitForFunction(()=>document.querySelectorAll('.dcw-book-card').length===23);
    await page.getByRole('checkbox',{name:'选择 作品 01',exact:true}).uncheck();
    await page.getByRole('button',{name:'前移 作品 02',exact:true}).click();
    await page.locator('#dcw-title-mode').selectOption('top');
    await page.locator('#dcw-title-text').fill('九月阅读清单');
    await page.locator('#dcw-page-format').selectOption('square');
    await page.locator('#dcw-book-search').fill('作品 02');
    assert.equal(await page.locator('.dcw-book-card').count(),1);
    await page.getByRole('button',{name:'成品预览',exact:true}).click();
    await page.waitForFunction(()=>document.querySelector('#dcw-output-canvas canvas'));
    assert.equal(await page.locator('#dcw-preview-page option').count(),2);
    assert.ok(await page.locator('.dcw-filterbar').isHidden());
    const first=await page.locator('#dcw-output-canvas canvas').evaluate(c=>({width:c.width,height:c.height,label:c.getAttribute('aria-label')}));
    assert.equal(first.width,1500);assert.equal(first.height,1500);
    const fits=await page.evaluate(()=>document.querySelector('#dcw-output-canvas canvas').getBoundingClientRect().bottom <= document.querySelector('.dcw-canvas-shell').getBoundingClientRect().bottom);
    assert.ok(fits,'Fit-page mode must show the whole canvas');
    assert.ok(first.label.includes('作品 02'));assert.ok(!first.label.includes('作品 01'));
    await page.getByRole('button',{name:'下一页',exact:true}).click();
    await page.waitForFunction(()=>document.querySelector('#dcw-output-canvas canvas')?.getAttribute('aria-label').startsWith('第 2 页'));
    assert.ok(await page.getByRole('button',{name:'下一页',exact:true}).isDisabled());
    await page.getByRole('button',{name:'上一页',exact:true}).click();
    await page.waitForFunction(()=>document.querySelector('#dcw-output-canvas canvas')?.getAttribute('aria-label').startsWith('第 1 页'));
    const previewPNG=await page.locator('#dcw-output-canvas canvas').evaluate(c=>c.toDataURL());
    const downloadPromise=page.waitForEvent('download');
    await page.getByRole('button',{name:'导出 PNG',exact:true}).click();
    const download=await downloadPromise;
    const output=path.join(__dirname,'../output/playwright');fs.mkdirSync(output,{recursive:true});
    const downloadedFile=path.join(output,'export-page-01.png');await download.saveAs(downloadedFile);
    const difference=await page.evaluate(async ([a,b])=>{
      async function pixels(src){const img=new Image();img.src=src;await img.decode();const c=document.createElement('canvas');c.width=img.width;c.height=img.height;const ctx=c.getContext('2d');ctx.drawImage(img,0,0);return ctx.getImageData(0,0,c.width,c.height).data;}
      const first=await pixels(a),second=await pixels(b);let count=0;for(let i=0;i<first.length;i++)if(first[i]!==second[i])count++;return count;
    },[previewPNG,'data:image/png;base64,'+fs.readFileSync(downloadedFile).toString('base64')]);
    assert.equal(difference,0,'Preview/export pixels must match (PNG encoders may differ)');
    await page.waitForFunction(()=>!document.querySelector('[data-action="export"]').disabled);
    await page.screenshot({path:path.join(output,'preview.png')});
    await page.reload();
    await page.locator('#dcw-launcher').click();
    await page.waitForFunction(()=>document.querySelectorAll('.dcw-book-card').length===23);
    assert.equal(await page.locator('#dcw-title-text').inputValue(),'九月阅读清单');
    assert.equal(await page.locator('#dcw-page-format').inputValue(),'square');
    assert.ok(!(await page.getByRole('checkbox',{name:'选择 作品 01',exact:true}).isChecked()));
    assert.ok((await page.locator('.dcw-book-card').first().innerText()).includes('作品 02'));
    await page.getByRole('button',{name:'更新作品',exact:true}).click();
    await page.waitForFunction(()=>!document.querySelector('[data-action="refresh-books"]').disabled);
    assert.ok(!(await page.getByRole('checkbox',{name:'选择 作品 01',exact:true}).isChecked()));
    assert.ok((await page.locator('.dcw-book-card').first().innerText()).includes('作品 02'));
    await page.screenshot({path:path.join(output,'organizer.png')});
    await page.goto('http://127.0.0.1:8768/personage/2/creations?type=writer');
    await page.locator('#dcw-launcher').click();
    await page.waitForFunction(()=>document.querySelectorAll('.dcw-book-card').length===23);
    assert.ok(await page.getByRole('checkbox',{name:'选择 作品 01',exact:true}).isChecked());
    assert.ok((await page.locator('.dcw-book-card').first().innerText()).includes('作品 01'));
    await page.getByRole('button',{name:'反选全部作品',exact:true}).click();
    await page.getByRole('button',{name:'成品预览',exact:true}).click();
    await page.waitForFunction(()=>document.querySelector('#dcw-preview-status').textContent.includes('至少选择'));
    assert.equal(await page.locator('#dcw-output-canvas canvas').count(),0);
    await page.getByRole('button',{name:'整理作品',exact:true}).click();
    await page.getByRole('button',{name:'选择全部作品',exact:true}).click();
    await page.evaluate(()=>sessionStorage.setItem('failCover','1'));
    await page.getByRole('button',{name:'成品预览',exact:true}).click();
    await page.waitForFunction(()=>document.querySelector('#dcw-preview-status').textContent.includes('占位'));
    assert.equal(await page.locator('#dcw-output-canvas canvas').count(),1);
    await page.evaluate(()=>sessionStorage.removeItem('failCover'));
    await page.getByRole('button',{name:'重新载入',exact:true}).click();
    await page.waitForFunction(()=>document.querySelector('#dcw-preview-status').textContent.includes('相同画幅'));
    await page.getByRole('button',{name:'下一页',exact:true}).click();
    await page.getByRole('button',{name:'上一页',exact:true}).click();
    await page.waitForFunction(()=>document.querySelector('#dcw-output-canvas canvas')?.getAttribute('aria-label').startsWith('第 1 页'));
    await page.waitForTimeout(500);
    assert.ok((await page.locator('#dcw-output-canvas canvas').getAttribute('aria-label')).startsWith('第 1 页'));
    assert.deepEqual(errors,[]);
    console.log('PASS: selection, ordering, search separation, pagination, preview/export pixel equality, draft reload, refresh merge, page isolation, empty selection, failed covers/retry, rapid navigation; no page errors.');
  } finally {await browser.close();}
})().catch(error=>{console.error(error);process.exitCode=1;});
